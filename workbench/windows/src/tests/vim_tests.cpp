#include "../app.h"

int App::vimTest(const fs::path& report) {
    using V = orbit::VimEditor;
    json results = json::array(), timings = json::object();
    const auto check = [&](const char* name, bool passed) { results.push_back({{"name", name}, {"passed", passed}}); };
    // An isolated native control: no user document, disk file, clipboard or language session is edited.
    const auto control = CreateWindowExW(0, L"Scintilla", L"", WS_CHILD, 0, 0, 800, 600, window, nullptr, instance, nullptr);
    const auto send = [control](UINT message, WPARAM w = 0, LPARAM l = 0) { return SendMessageW(control, message, w, l); };
    V v; v.attach(control); v.enable(true);
    send(SCI_SETCODEPAGE, SC_CP_UTF8); send(SCI_SETTABWIDTH, 4); send(SCI_SETINDENT, 4); send(SCI_SETUSETABS, FALSE);
    const auto reset = [&](const std::string& value, sptr_t at = 0, int eol = SC_EOL_LF) {
        v.leaveDocument(); send(SCI_SETREADONLY, FALSE); send(SCI_SETTEXT, 0, reinterpret_cast<LPARAM>(value.c_str()));
        send(SCI_EMPTYUNDOBUFFER); send(SCI_SETEOLMODE, eol); send(SCI_SETSEL, at, at);
    };
    const auto text = [&] {
        const auto size = send(SCI_GETLENGTH); std::string value(size + 1, 0);
        send(SCI_GETTEXT, value.size(), reinterpret_cast<LPARAM>(value.data())); value.resize(size); return value;
    };
    const auto keys = [&](std::string_view value) { for (const unsigned char key : value) v.feed(key); };
    const auto at = [&] { return send(SCI_GETCURRENTPOS); };
    const auto escape = [&] { v.feed(V::Escape); };
    try {
        reset("abc\ndef\nghi\n"); keys("2lj0k");
        check("counts_and_hjkl_motions", at() == 0);
        keys("G"); check("G_reaches_last_line", at() == 12);
        keys("2gg"); check("count_gg_reaches_line", at() == 4);
        keys("$"); check("normal_caret_stays_on_last_character", at() == 6);
        keys("lll"); check("l_does_not_cross_eol", at() == 6);
        reset("  alpha beta.gamma\n"); keys("^w"); check("word_forward", at() == 8);
        keys("e"); check("word_end", at() == 11);
        keys("b"); check("word_back", at() == 8);
        keys("0W"); check("WORD_skips_whitespace", at() == 2);
        reset("one two three\n"); keys("dw"); check("delete_word", text() == "two three\n");
        keys("u"); check("delete_word_one_undo", text() == "one two three\n");
        v.feed(V::Redo); check("ctrl_r_redo", text() == "two three\n");
        reset("1 2 3 4 5 6 7\n"); keys("2d3w"); check("operator_counts_multiply", text() == "7\n");
        reset("one two\n"); keys("cwNEW"); escape(); check("cw_keeps_following_space", text() == "NEW two\n");
        keys("u"); check("change_and_insert_one_undo", text() == "one two\n");
        reset("one two three\n"); keys("cwNEW"); escape(); keys("w.");
        check("dot_repeats_change_and_insert", text() == "NEW NEW three\n");
        reset("abcdef\n"); keys("x2."); check("dot_count_replaces_original_count", text() == "def\n");
        reset("z\n"); keys("3iab"); escape(); check("counted_insert", text() == "abababz\n");
        keys("u"); check("counted_insert_single_undo", text() == "z\n");
        v.feed(V::Redo); keys("$."); check("dot_replays_counted_insert", text() == "ababababababz\n");
        reset("one\ntwo\nthree\n"); keys("2dd"); check("counted_line_delete", text() == "three\n");
        keys("P"); check("line_register_paste_before", text() == "one\ntwo\nthree\n");
        reset("one\ntwo"); keys("jdd"); check("delete_final_unterminated_line", text() == "one");
        keys("p"); check("paste_unterminated_line_adds_separator", text() == "one\ntwo\n");
        reset("a\n"); keys("Gdd"); check("delete_empty_last_line_removes_whole_eol", text() == "a");
        reset("one\ntwo\n"); keys("ccNEW"); escape(); check("line_change_preserves_following_line", text() == "NEW\ntwo\n");
        keys("u"); check("line_change_one_undo", text() == "one\ntwo\n");
        reset("    old\nnext\n"); keys("ccNEW"); escape(); check("line_change_retains_autoindent", text() == "    NEW\nnext\n");
        reset("abc\n"); keys("\"ayl$x\"aP"); check("named_character_register", text() == "aab\n");
        reset("abc\n"); keys("yl\"_xP"); check("black_hole_preserves_unnamed_register", text() == "abc\n");
        reset("one two\n"); keys("\"ayw\"Ayw\"aP"); check("uppercase_register_appends", text() == "one one one two\n");
        reset("hello world\n", 2); keys("diw"); check("inner_word_object", text() == " world\n");
        reset("hello world\n", 2); keys("daw"); check("around_word_object", text() == "world\n");
        reset("hello   world next\n", 6); keys("daw"); check("around_word_on_whitespace_includes_next_word", text() == "hello next\n");
        reset("f(a, (b + c))\n", 7); keys("ci(NEW"); escape(); check("nested_parenthesis_object", text() == "f(a, (NEW))\n");
        reset("value = 'a\\'b'\n", 10); keys("di'"); check("quoted_object_handles_escaped_quote", text() == "value = ''\n");
        reset("x = [one, two]\n", 6); keys("da["); check("around_bracket_object", text() == "x = \n");
        reset("abc def\n"); keys("vld"); check("visual_character_inclusive_delete", text() == "c def\n");
        keys("u"); check("visual_delete_one_undo", text() == "abc def\n");
        reset("one\ntwo\nthree\n"); keys("Vjy"); keys("Gp"); check("visual_line_yank", text() == "one\ntwo\nthree\none\ntwo\n");
        reset("hello world\n", 2); keys("viwy"); check("visual_text_object_yank_no_edit", text() == "hello world\n" && v.mode() == V::Mode::Normal);
        reset("abc\ndef\n"); keys("vll"); escape(); check("visual_escape_retains_actual_caret", at() == 2 && send(SCI_GETSELECTIONSTART) == send(SCI_GETSELECTIONEND));
        reset("abcxdefx\n"); keys("fx"); check("find_character", at() == 3);
        keys(";"); check("repeat_character_find", at() == 7);
        keys(","); check("reverse_character_find", at() == 3);
        reset("abcxdef\n"); keys("dtx"); check("operator_till_character", text() == "xdef\n");
        reset("abxcdef\n", 6); keys("dFx"); check("backward_find_operator_includes_cursor", text() == "ab\n");
        reset("abxcdef\n", 6); keys("dTx"); check("backward_till_operator_excludes_found_character", text() == "abx\n");
        reset("abxcdefxghi\n"); keys("tx;"); check("repeat_till_skips_adjacent_previous_match", at() == 6);
        reset("\nnext\n"); keys("d$"); check("delete_to_end_of_empty_line_preserves_eol", text() == "\nnext\n");
        reset("(abc)\n"); keys("%"); check("matching_brace_motion", at() == 4);
        reset("(abc)\n"); keys("d%"); check("matching_brace_operator_inclusive", text() == "\n");
        reset("abc\n"); keys("2r"); v.feed(U'中'); check("unicode_replace_character", text() == "中中c\n");
        reset("a\n"); keys("2rX"); check("replace_count_cannot_extend_line", text() == "a\n");
        reset("你好🙂 world\r\n次行\r\n", 0, SC_EOL_CRLF); keys("lx");
        check("utf8_motion_delete_codepoint", text() == "你🙂 world\r\n次行\r\n");
        keys("u"); keys("$l"); check("normal_caret_avoids_crlf_bytes", at() == 15);
        reset("甲\r\n乙\r\n", 0, SC_EOL_CRLF); keys("ddp"); check("line_yank_paste_preserves_crlf", text() == "乙\r\n甲\r\n");
        reset("ab\r\ncd", 4, SC_EOL_CRLF); keys("i"); v.feed(V::Backspace); escape();
        check("insert_backspace_treats_crlf_as_unit", text() == "abcd");
        reset("ab\n"); keys("i"); v.feed(U'中'); v.feed(0x1f642); escape();
        check("insert_unicode_and_supplementary_codepoint", text() == "中🙂ab\n");
        reset("x\n"); keys("iabc"); v.pointerInput(); keys("Z"); escape(); keys("u");
        check("mouse_or_focus_boundary_splits_insert_undo", text() == "abcx\n");
        keys("u"); check("earlier_insert_segment_keeps_undo", text() == "x\n");
        reset("  one\r\nnext", 0, SC_EOL_CRLF); keys("oX"); escape();
        check("open_line_preserves_eol_and_indent", text() == "  one\r\n  X\r\nnext");
        reset("x\n"); keys("i"); v.feed(V::Tab); v.feed(V::Enter); keys("y"); escape();
        check("insert_tab_and_autoindent", text() == "    \n    yx\n");
        reset("one\ntwo\nthree"); keys("qaI#"); escape(); keys("jq"); keys("2@a");
        check("record_and_counted_macro_playback", text() == "#one\n#two\n#three");
        keys("@@"); check("repeat_last_macro", text() == "#one\n#two\n##three");
        keys("u"); check("macro_changes_use_native_undo", text() == "#one\n#two\n#three");
        reset("abc abc abc\n"); keys("/abc"); v.feed(V::Enter); check("literal_search", at() == 4);
        keys("n"); check("search_next", at() == 8);
        keys("n"); check("search_wraps", at() == 0);
        keys("N"); check("search_reverse", at() == 8);
        reset("cat catch cat\n"); keys("*"); check("word_search_respects_boundaries", at() == 10);
        reset("a\nb\nc\n"); keys(":2"); v.feed(V::Enter); check("ex_line_number", at() == 2);
        keys(":w"); v.feed(V::Enter); check("ex_save_dispatches_to_host", v.takeHostCommand() == "save");
        keys(":wa"); v.feed(V::Enter); check("ex_write_all_dispatch", v.takeHostCommand() == "save-all");
        keys(":wq"); v.feed(V::Enter); check("ex_save_close_dispatch", v.takeHostCommand() == "save-close");
        keys(":!anything"); v.feed(V::Enter); check("unsupported_ex_never_starts_shell", v.takeHostCommand().empty() && v.status().find("Unsupported") != std::string::npos);
        reset("a\nb\n"); keys(">>j>>"); check("indent_line_operators", text() == "    a\n    b\n");
        keys("<<"); check("unindent_line_operator", text() == "    a\nb\n");
        reset("a\n    b\n"); keys("J"); check("join_lines", text() == "a b\n");
        keys("u"); check("join_is_one_undo", text() == "a\n    b\n");
        reset("abc\n"); keys("d"); escape(); keys("l"); check("escape_cancels_pending_operator", text() == "abc\n" && at() == 1);
        keys("iX"); v.leaveDocument(); keys("x"); check("document_switch_finishes_insert_and_resets_mode", text() == "aXc\n" && v.mode() == V::Mode::Normal);
        keys("u"); keys("u"); check("document_switch_does_not_leave_open_undo_group", text() == "abc\n");
        reset("abc\n"); send(SCI_SETREADONLY, TRUE); keys("dd"); check("readonly_document_is_not_modified", text() == "abc\n");
        send(SCI_SETREADONLY, FALSE);
        reset("abc\n"); v.enable(false); keys("dd"); check("disabled_controller_does_nothing", text() == "abc\n" && send(SCI_GETCARETSTYLE) == CARETSTYLE_LINE); v.enable(true);
        check("normal_mode_uses_native_block_caret", send(SCI_GETCARETSTYLE) == CARETSTYLE_BLOCK);
        keys("i"); check("insert_mode_uses_line_caret", send(SCI_GETCARETSTYLE) == CARETSTYLE_LINE); escape();

        std::string large; large.reserve(10 * 1024 * 1024);
        while (large.size() < 10 * 1024 * 1024) large += "alpha beta gamma\n";
        reset(large);
        const auto before = v.copiedBytes();
        const auto began = Clock::now();
        for (int i = 0; i < 5000; ++i) keys("j0wl");
        timings["20000_motions_10MiB_ms"] = std::chrono::duration<double, std::milli>(Clock::now() - began).count();
        check("large_file_motions_copy_zero_document_bytes", v.copiedBytes() == before && at() > 0);
        reset(std::string(V::registerLimit + 2, 'x'));
        keys("dd"); check("oversized_register_delete_is_rejected_without_data_loss", send(SCI_GETLENGTH) == V::registerLimit + 2 && v.status().find("Register limit") != std::string::npos);
        keys("\"_dd"); check("black_hole_allows_large_delete_without_copy", send(SCI_GETLENGTH) == 0 && v.copiedBytes() == before);
        reset(std::string(2 * 1024 * 1024, 'x')); keys("w");
        check("pathological_word_scan_is_bounded", at() == 0 && v.status().find("scan limit") != std::string::npos);

        V recursive; recursive.attach(control); recursive.enable(true);
        for (auto c : std::string("qa@bqqb@aq@a")) recursive.feed(c);
        check("recursive_macros_have_depth_limit", recursive.status().find("recursion limit") != std::string::npos);
        recursive.leaveDocument();

        // Exercise the application's real WM_CHAR adapter on a temporary document.
        std::string previousSession;
        try { previousSession = readFile(dataDir / L"session.json"); } catch (...) {}
        const auto previousActive = active;
        const auto previousSettings = settings;
        const auto previousPointer = sci(SCI_GETDOCPOINTER);
        sci(SCI_ADDREFDOCUMENT, 0, previousPointer);
        const auto temporary = sci(SCI_CREATEDOCUMENT);
        const auto previousSuppress = suppress; suppress = true;
        vim.leaveDocument(); sci(SCI_SETDOCPOINTER, 0, temporary); sci(SCI_SETREADONLY, FALSE);
        active = "__vim_test__.txt"; settings.vim = true; configureVim();
        sci(SCI_SETTEXT, 0, reinterpret_cast<sptr_t>("abc\n")); sci(SCI_SETSEL, 0, 0); sci(SCI_EMPTYUNDOBUFFER);
        SetFocus(editor);
        SendMessageW(editor, WM_CHAR, 'i', 0);
        SendMessageW(editor, WM_CHAR, 0xd83d, 0); SendMessageW(editor, WM_CHAR, 0xde42, 0);
        SendMessageW(editor, WM_CHAR, 0x4e2d, 0);
        vim.feed(V::Escape);
        check("wm_char_adapter_combines_utf16_surrogates", currentText() == "🙂中abc\n");
        const auto oldFocus = GetFocus(); SetFocus(searchEdit);
        const auto editorBeforeFocusKey = currentText(); vimCharacter('x');
        check("stale_editor_char_is_ignored_after_focus_change", currentText() == editorBeforeFocusKey);
        check("vim_shortcuts_ignore_non_editor_focus", !vimKey('D', true, false, false));
        SetFocus(editor);
        check("ctrl_f_is_vim_page_motion", vimKey('F', true, false, false));
        check("ctrl_shift_f_preserves_project_search", !vimKey('F', true, true, false));
        check("ctrl_s_preserves_workbench_save", !vimKey('S', true, false, false));
        sci(SCI_SETSEL, 0, 0); vim.feed('d');
        SetFocus(searchEdit); SetFocus(editor);
        SendMessageW(editor, WM_CHAR, 'l', 0);
        check("focus_loss_cancels_pending_operator", currentText() == "🙂中abc\n");
        saveSession();
        check("vim_setting_persists", json::parse(readFile(dataDir / L"session.json"))["settings"]["vim"] == true);
        settings.vim = false; loadSession(); check("vim_setting_reloads", settings.vim);
        vim.leaveDocument(); sci(SCI_SETDOCPOINTER, 0, previousPointer);
        sci(SCI_RELEASEDOCUMENT, 0, previousPointer); sci(SCI_RELEASEDOCUMENT, 0, temporary);
        active = previousActive; settings = previousSettings; configureVim(); suppress = previousSuppress;
        if (oldFocus) SetFocus(oldFocus);
        if (!previousSession.empty()) atomicWrite(dataDir / L"session.json", previousSession);
    } catch (const std::exception& error) {
        results.push_back({{"name", "unexpected_exception"}, {"passed", false}, {"error", error.what()}});
    }
    v.leaveDocument(); DestroyWindow(control);
    bool passed = true; for (const auto& result : results) if (!result["passed"].get<bool>()) passed = false;
    atomicWrite(report, json{{"passed", passed}, {"checks", results.size()}, {"results", results}, {"timings", timings},
        {"scope", "Real isolated Scintilla editing and command dispatch. Timing is synchronous controller work, not input-to-screen latency."}}.dump(2));
    return passed ? 0 : 1;
}
